    private void tampilkan(ArrayList<Buku> list) {
        String[] kolom = {"ID", "Kategori", "Judul", "Penulis", "Penerbit"};
        DefaultTableModel model = new DefaultTableModel(kolom, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };
        for (Buku b : list) {
            model.addRow(new Object[]{
                b.getIdbuku(), b.getKategori().getNama(),
                b.getJudul(), b.getPenulis(), b.getPenerbit()
            });
        }
        tblBuku.setModel(model);
    }

    public void tampilkanData() {
        tampilkan(new Buku().getAll());
    }
