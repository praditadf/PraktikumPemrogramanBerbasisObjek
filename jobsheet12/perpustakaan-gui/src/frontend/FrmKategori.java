    private void tampilkan(ArrayList<Kategori> list) {
        String[] kolom = {"ID", "Nama", "Keterangan"};
        DefaultTableModel model = new DefaultTableModel(kolom, 0) {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        for (Kategori kat : list) {
            model.addRow(new Object[]{
                kat.getIdkategori(), kat.getNama(), kat.getKeterangan()
            });
        }
        tblKategori.setModel(model);
    }

    public void tampilkanData() {
        tampilkan(new Kategori().getAll());
    }

